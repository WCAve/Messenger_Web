#!/usr/bin/env node
/**
 * Regenerates web/src/emoji/extra.ts: every single-code-point emoji not in curated.ts, named after
 * its Unicode character name, plus all country flags (:flag_nl: etc.).
 *
 * Needs the `emoji-regex` package (any recent version) and python3 for Unicode names:
 *   NODE_PATH=/path/to/node_modules node web/scripts/gen-emoji.mjs
 */
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const emojiRegex = require('emoji-regex');
const here = path.dirname(fileURLToPath(import.meta.url));
const strip = (s) => s.replace(/️/g, '');

const curatedSrc = fs.readFileSync(path.join(here, '../src/emoji/curated.ts'), 'utf8');
const curated = new Set(
  curatedSrc
    .split('\n')
    .filter((l) => l && !l.startsWith('# ') && !l.startsWith('`') && /^\S+\s/.test(l))
    .map((l) => strip(l.split(' ')[0])),
);

const re = emojiRegex();
const full = new RegExp(`^(?:${re.source})$`, re.flags.replace('g', ''));
// Every assigned code point in these blocks is an emoji, including ones newer than emoji-regex knows.
const alwaysEmoji = (cp) => (cp >= 0x1f90c && cp <= 0x1f9ff) || (cp >= 0x1fa70 && cp <= 0x1faff);
const ranges = [
  [0x2100, 0x2bff],
  [0x3030, 0x303d],
  [0x3297, 0x3299],
  [0x1f000, 0x1faff],
];
const candidates = [];
for (const [a, b] of ranges) {
  for (let cp = a; cp <= b; cp++) {
    const ch = String.fromCodePoint(cp);
    if (cp >= 0x1f1e6 && cp <= 0x1f1ff) continue; // regional indicators: flags handled below
    if (cp >= 0x1f3fb && cp <= 0x1f3ff) continue; // skin tone modifiers
    const asEmoji = full.test(ch) || alwaysEmoji(cp) ? ch : full.test(ch + '️') ? ch + '️' : null;
    if (asEmoji && !curated.has(strip(asEmoji))) candidates.push([cp, asEmoji]);
  }
}

const names = JSON.parse(
  execFileSync('python3', ['-c', 'import sys,json,unicodedata as u; print(json.dumps([u.name(chr(c),"") for c in json.load(sys.stdin)]))'], {
    input: JSON.stringify(candidates.map(([cp]) => cp)),
  }).toString(),
);

const lines = [];
candidates.forEach(([, e], i) => {
  const name = names[i];
  if (!name) return; // newer than this Python's Unicode database
  const code = name.toLowerCase().replace(/[^a-z0-9]+/g, '_').replace(/^_|_$/g, '');
  lines.push(`${e} ${code}`);
});

// Flags: every ISO 3166 region the runtime knows a name for.
const regions = new Intl.DisplayNames(['en'], { type: 'region' });
for (let a = 65; a <= 90; a++) {
  for (let b = 65; b <= 90; b++) {
    const cc = String.fromCharCode(a, b);
    let name;
    try {
      name = regions.of(cc);
    } catch {
      continue;
    }
    if (!name || name === cc) continue;
    const flag = String.fromCodePoint(0x1f1e6 + a - 65, 0x1f1e6 + b - 65);
    if (!full.test(flag)) continue;
    const words = name.toLowerCase().replace(/[^a-z0-9 ]+/g, ' ').trim();
    lines.push(`${flag} flag_${cc.toLowerCase()} | flag ${words}`);
  }
}

const out = `// Generated by web/scripts/gen-emoji.mjs — do not edit by hand.\nexport const EXTRA = \`\n${lines.join('\n')}\n\`;\n`;
fs.writeFileSync(path.join(here, '../src/emoji/extra.ts'), out);
console.log(`wrote ${lines.length} emoji to src/emoji/extra.ts`);
