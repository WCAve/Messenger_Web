"""Sign-in (wrong and right password), linking Signal by QR code, first chat list, opening a chat."""
import sys, time
from playwright.sync_api import sync_playwright
S = sys.argv[1]
errors = []
with sync_playwright() as p:
    b = p.chromium.launch()
    ctx = b.new_context(viewport={'width': 1280, 'height': 800})
    page = ctx.new_page()
    page.on('console', lambda m: m.type == 'error' and errors.append(m.text))
    page.on('pageerror', lambda e: errors.append(str(e)))
    page.goto('http://localhost:3000/')
    page.fill('input[type=password]', 'wrongpassword')
    page.click('button:has-text("Sign in")')
    page.wait_for_selector('.form-error')
    page.screenshot(path=f'{S}/shots/01-login-error.png')
    page.fill('input[type=password]', 'testpassword')
    page.click('button:has-text("Sign in")')
    page.wait_for_selector('.qr-frame img', timeout=10000)
    page.screenshot(path=f'{S}/shots/02-link.png')
    page.wait_for_selector('.chat-row', timeout=20000)
    time.sleep(1)
    page.screenshot(path=f'{S}/shots/03-list.png')
    page.click('.chat-row:has-text("Alice")')
    page.wait_for_selector('.msg')
    time.sleep(1)
    page.screenshot(path=f'{S}/shots/04-alice.png')
    # reply to first message
    first = page.locator('.msg.in').first
    first.hover()
    first.locator('button[aria-label=Reply]').click()
    page.fill('textarea', 'Saturday it is 🎉')
    page.keyboard.press('Enter')
    page.wait_for_selector('.typing-text', timeout=8000)
    page.screenshot(path=f'{S}/shots/05-typing.png')
    page.wait_for_selector('text=Got it', timeout=10000)
    # react to the reply
    last_in = page.locator('.msg.in').last
    last_in.hover()
    last_in.locator('button[aria-label=React]').click()
    page.locator('.quick-react button').nth(1).click()
    page.wait_for_selector('.reaction.mine', timeout=5000)
    time.sleep(0.5)
    page.screenshot(path=f'{S}/shots/06-sent-reacted.png')
    # failed send + attachment
    page.set_input_files('input[type=file]', files=[{'name': 'notes.txt', 'mimeType': 'text/plain', 'buffer': b'hello there'}])
    page.fill('textarea', 'this will fail')
    page.keyboard.press('Enter')
    page.wait_for_selector('.failed-note', timeout=8000)
    page.screenshot(path=f'{S}/shots/07-failed.png')
    # group
    page.click('.chat-row:has-text("Weekend")')
    page.wait_for_selector('.msg .author', timeout=15000)
    time.sleep(0.5)
    page.screenshot(path=f'{S}/shots/08-group.png')
    # lightbox
    page.click('.chat-row:has-text("Alice")')
    page.click('.img-btn')
    page.wait_for_selector('.lightbox')
    page.screenshot(path=f'{S}/shots/09-lightbox.png')
    page.keyboard.press('Escape')
    # new chat
    page.click('button[aria-label="New chat"]')
    page.fill('.search input', '+31 6 44444444')
    page.screenshot(path=f'{S}/shots/10-newchat.png')
    page.keyboard.press('Enter')
    page.wait_for_selector('.chat-head h2:has-text("+31644444444")', timeout=5000)
    page.fill('textarea', 'Hi stranger')
    page.keyboard.press('Enter')
    time.sleep(1.5)
    page.screenshot(path=f'{S}/shots/11-newchat-sent.png')
    # mobile + dark
    m = b.new_context(viewport={'width': 390, 'height': 780}, color_scheme='dark', storage_state=ctx.storage_state())
    mp = m.new_page()
    mp.on('pageerror', lambda e: errors.append(str(e)))
    mp.goto('http://localhost:3000/')
    mp.wait_for_selector('.chat-row')
    time.sleep(0.5)
    mp.screenshot(path=f'{S}/shots/12-mobile-list-dark.png')
    mp.click('.chat-row:has-text("Alice")')
    mp.wait_for_selector('.msg')
    time.sleep(0.8)
    mp.screenshot(path=f'{S}/shots/13-mobile-chat-dark.png')
    b.close()
print('ERRORS:', errors)
